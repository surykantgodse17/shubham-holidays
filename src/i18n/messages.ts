function buildCatalog(locale: LocaleCode): Dictionary {
  if (locale === "en") return en;
  if (locale === "mr") return mr;
  if (locale === "hi") return hi;
  return { ...en, ...(partial[locale] ?? {}) };
}

const catalogs = Object.fromEntries(
  (Object.keys(partial) as LocaleCode[])
    .concat(["en", "mr", "hi"])
    .filter((v, i, a) => a.indexOf(v) === i)
    .map((code) => [code, buildCatalog(code)]),
) as Record<LocaleCode, Dictionary>;

// Ensure every LocaleCode has an entry (TypeScript + runtime safety)
for (const code of [
  "en", "mr", "hi", "gu", "bn", "ta", "te", "kn", "ml", "pa", "or", "as", "ur", "sa",
  "ne", "kok", "ks", "sd", "mai", "sat", "mni", "doi", "brx",
  "es", "fr", "de", "pt", "ar", "zh", "ja", "ko", "ru", "it", "id", "th", "tr",
] as LocaleCode[]) {
  if (!catalogs[code]) catalogs[code] = buildCatalog(code);
}

export function translate(locale: LocaleCode, key: MessageKey): string {
  return catalogs[locale]?.[key] ?? en[key] ?? key;
}
